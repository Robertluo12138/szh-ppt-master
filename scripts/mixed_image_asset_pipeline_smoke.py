def _materialize_bundle(
    td: Path,
    *,
    with_source_assets: bool = True,
    local_asset_payload: bytes = _LOCAL_ASSET_PNG_BYTES,
    image_manifest_spec_overrides: dict | None = None,
    d_one_spec_overrides: dict | None = None,
    local_asset_dst_local_path: str | None = None,
) -> dict:
    """Write the synthetic mixed-lane bundle under ``<td>/bundle/`` and
    return a dict of resolved paths.

    ``with_source_assets`` controls whether ``<bundle>/source_assets/``
    is created (False is the P1 missing-source_assets probe).
    ``local_asset_payload`` lets a probe inject magic-byte-invalid
    bytes (P2). ``image_manifest_spec_overrides`` lets P4 inject a
    local_path collision; ``d_one_spec_overrides`` lets P3 leak the
    local_asset id into the d_one_spec.
    ``local_asset_dst_local_path`` lets the staging copy land at a
    different name than the manifest entry's local_path (used by P2
    to ensure the magic-byte gate fires before any extension swap)."""
    bundle = td / "bundle"
    bundle.mkdir(parents=True)
    source = bundle / "source.md"
    source.write_text(_source_md(), encoding="utf-8")

    _write_json(bundle / "brief.json", _brief_body())
    _write_json(bundle / "plan_spec.json", _plan_spec_body())
    _write_json(bundle / "design_system_spec.json", _design_system_body())

    slide_specs = bundle / "slide_specs"
    slide_specs.mkdir()
    _write_json(
        slide_specs / "01_cover.json",
        _slide_cover_body(
            index=1, title=D_ONE_SLIDE_TITLE, image_id=D_ONE_IMAGE_ID,
        ),
    )
    _write_json(
        slide_specs / "02_cover.json",
        _slide_cover_body(
            index=2, title=LOCAL_ASSET_SLIDE_TITLE,
            image_id=LOCAL_ASSET_IMAGE_ID,
        ),
    )

    manifest_body = _image_manifest_spec_body()
    if image_manifest_spec_overrides is not None:
        manifest_body = image_manifest_spec_overrides
    _write_json(bundle / "image_manifest_spec.json", manifest_body)

    d_one_body = _d_one_spec_body()
    if d_one_spec_overrides is not None:
        d_one_body = d_one_spec_overrides
    _write_json(bundle / "d_one_spec.json", d_one_body)

    if with_source_assets:
        source_assets = bundle / "source_assets"
        source_assets.mkdir()
        dst_local = (
            local_asset_dst_local_path
            if local_asset_dst_local_path is not None
            else LOCAL_ASSET_LOCAL_PATH
        )
        leaf = source_assets / dst_local
        leaf.parent.mkdir(parents=True, exist_ok=True)
        leaf.write_bytes(local_asset_payload)

    return {
        "bundle": bundle,
        "source": source,
    }


