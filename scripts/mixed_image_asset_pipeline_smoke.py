def _run_positive_chain(td: Path) -> tuple[bool, list[Assertion]]:
    print("--- positive proof (mixed lane: d_one_local + local_asset) ---")
    workspace = td / "workspace"
    output = td / "mixed.pptx"
    report_dir = td / "report"
    bundle = _materialize_bundle(td)
    print(f"  bundle:       {bundle['bundle']}")
    print(f"  workspace:    {workspace}")
    print(f"  pptx output:  {output}")
    print(f"  report dir:   {report_dir}")
    print(
        f"  local_asset sha256={_LOCAL_ASSET_PNG_SHA256[:16]}... "
        f"({len(_LOCAL_ASSET_PNG_BYTES)} bytes)"
    )

    runner = _run(
        "run_mock_image_pipeline (mixed-lane bundle)",
        _runner_args(
            bundle_dir=bundle["bundle"], workspace=workspace,
            output=output, report_dir=report_dir,
        ),
    )
    _print_outcome(runner)
    if not runner.ok:
        return False, [Assertion(
            "run_mock_image_pipeline returns rc=0",
            False,
            f"rc={runner.rc}; "
            f"tail={runner.combined.splitlines()[-20:]!r}",
        )]

    assertions: list[Assertion] = []

    pptx_is_file = output.is_file() and not output.is_symlink()
    assertions.append(Assertion(
        "final PPTX exists as a regular non-symlink file",
        pptx_is_file, f"path={output}",
    ))
    if pptx_is_file:
        size = output.stat().st_size
        assertions.append(Assertion(
            "final PPTX is non-empty",
            size > 0, f"size={size}",
        ))
        assertions.extend(
            _assert_pptx_relationships_internal_only(output)
        )

    # Contract validator with --expected-slide-count 2.
    contract = _run(
        "validate_pptx_contract --expected-slide-count 2",
        [
            sys.executable, str(VALIDATE_PPTX_CONTRACT),
            "--pptx", str(output),
            "--expected-slide-count", "2",
        ],
    )
    _print_outcome(contract)
    assertions.append(Assertion(
        "validate_pptx_contract --expected-slide-count 2 returns rc=0",
        contract.ok,
        f"rc={contract.rc}; "
        f"tail={contract.combined.splitlines()[-15:]!r}",
    ))
    assertions.extend(_assert_contract_minimal_evidence_pass(contract))

    # Inventory readback. run_mock_image_pipeline writes inventory.json
    # via the downstream orchestrator under --report-dir.
    inv_assertions, inventory_media_shas = _assert_inventory_contract(
        inventory_path=report_dir / "inventory.json",
        local_asset_sha=_LOCAL_ASSET_PNG_SHA256,
    )
    assertions.extend(inv_assertions)

    # Cross-check the inventory media shas against the actual ZIP shas
    # for the generated-media lane-distinctness assertion. The PPTX
    # parses as ZIP; for every embeddable media part we record sha256
    # directly so the d_one_local sha is whichever observed sha is NOT
    # the local_asset sha.
    pptx_shas, pptx_err = _pptx_media_shas(output)
    if pptx_err is not None:
        assertions.append(Assertion(
            "PPTX opens as ZIP for media-sha walk",
            False, f"{type(pptx_err).__name__}: {pptx_err}",
        ))
    else:
        observed = set(pptx_shas.values())
        assertions.append(Assertion(
            "inventory.media_parts sha set covers every observed "
            "ppt/media/* sha (no inventory drift)",
            observed <= inventory_media_shas,
            f"observed={sorted(observed)!r}; "
            f"inventory={sorted(inventory_media_shas)!r}",
        ))
        d_one_shas = observed - {_LOCAL_ASSET_PNG_SHA256}
        assertions.append(Assertion(
            "at least one generated d_one_local media sha is byte-"
            "distinct from the local_asset sha (the two lanes "
            "produce independent bytes end-to-end)",
            bool(d_one_shas),
            f"observed_shas={sorted(observed)!r}; "
            f"local_asset_sha={_LOCAL_ASSET_PNG_SHA256!r}",
        ))

    # Audit sidecar: covers only the d_one_local request id.
    assertions.extend(
        _assert_sidecar_covers_only_d_one(report_dir / SIDECAR_FILENAME)
    )

    ok = all(a.ok for a in assertions)
    return ok, assertions


