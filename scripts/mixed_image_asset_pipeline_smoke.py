@dataclass
class ProbeResult:
    name: str
    ok: bool
    detail: str = ""


def _probe_runner_fails(
    *,
    name: str,
    td: Path,
    bundle_dir: Path,
    expected_substrings: list[str],
) -> ProbeResult:
    """Drive run_mock_image_pipeline against ``bundle_dir`` and assert
    rc != 0 AND no .pptx lands at the nominated --output."""
    workspace = td / "workspace"
    output = td / "should_not_exist.pptx"
    report_dir = td / "report"
    outcome = _run(
        "run_mock_image_pipeline (probe)",
        _runner_args(
            bundle_dir=bundle_dir, workspace=workspace,
            output=output, report_dir=report_dir,
        ),
    )
    diagnostics: list[str] = []
    if outcome.ok:
        diagnostics.append(
            f"rc=0 (expected non-zero); "
            f"tail={outcome.combined.splitlines()[-20:]!r}"
        )
    missing = [s for s in expected_substrings if s not in outcome.combined]
    if missing:
        diagnostics.append(
            f"expected diagnostic substring(s) {missing!r} not found; "
            f"tail={outcome.combined.splitlines()[-20:]!r}"
        )
    if output.exists() or output.is_symlink():
        diagnostics.append(
            f"--output {output} exists after fail-closed run; "
            f"the runner must not leave a stray .pptx on failure"
        )
    return ProbeResult(
        name=name, ok=not diagnostics,
        detail="; ".join(diagnostics),
    )


def _probe_missing_source_assets() -> ProbeResult:
    """P1: bundle declares a local_asset entry but ships no
    <bundle>/source_assets/ AND --source-assets-dir is not passed."""
    with tempfile.TemporaryDirectory(
        prefix="szh_mixed_smoke_p1_",
    ) as raw_td:
        td = Path(raw_td)
        bundle = _materialize_bundle(td, with_source_assets=False)
        return _probe_runner_fails(
            name=(
                "P1: missing source_assets -> runner refuses at "
                "boundary (--source-assets-dir required for "
                "local_asset entries)"
            ),
            td=td,
            bundle_dir=bundle["bundle"],
            expected_substrings=[
                "local_asset", "--source-assets-dir",
            ],
        )


def _probe_wrong_local_asset_magic() -> ProbeResult:
    """P2: bundle ships <bundle>/source_assets/<local_path> whose first
    bytes do NOT match the PNG signature; _stage_local_assets' magic-
    byte gate fires."""
    with tempfile.TemporaryDirectory(
        prefix="szh_mixed_smoke_p2_",
    ) as raw_td:
        td = Path(raw_td)
        bundle = _materialize_bundle(
            td,
            local_asset_payload=(
                # 32 bytes that do NOT start with `\x89PNG\r\n\x1a\n`.
                b"NOT_A_PNG_HEADER_" + b"\x00" * 16
            ),
        )
        return _probe_runner_fails(
            name=(
                "P2: local_asset bytes fail PNG magic-byte gate -> "
                "_stage_local_assets refuses"
            ),
            td=td,
            bundle_dir=bundle["bundle"],
            expected_substrings=[
                "magic bytes", LOCAL_ASSET_LOCAL_PATH,
            ],
        )


def _probe_local_asset_id_in_d_one_spec() -> ProbeResult:
    """P3: bundle's d_one_spec.json lists the local_asset manifest id
    as a request; _check_d_one_spec_covers_generated's leaked-local-
    asset branch fires before any subprocess runs."""
    leaked_spec = {
        "requests": [
            {
                "id": D_ONE_IMAGE_ID,
                "prompt": (
                    "abstract calm geometric accent, no text, no logo"
                ),
                "intended_use": "spot illustration",
                "width_px": 320, "height_px": 320,
            },
            {
                "id": LOCAL_ASSET_IMAGE_ID,  # leaks here.
                "prompt": (
                    "abstract calm geometric accent, no text, no logo"
                ),
                "intended_use": "spot illustration",
                "width_px": 320, "height_px": 320,
            },
        ],
    }
    with tempfile.TemporaryDirectory(
        prefix="szh_mixed_smoke_p3_",
    ) as raw_td:
        td = Path(raw_td)
        bundle = _materialize_bundle(
            td, d_one_spec_overrides=leaked_spec,
        )
        return _probe_runner_fails(
            name=(
                "P3: local_asset id leaks into d_one_spec -> "
                "_check_d_one_spec_covers_generated refuses"
            ),
            td=td,
            bundle_dir=bundle["bundle"],
            expected_substrings=[
                "local_asset", LOCAL_ASSET_IMAGE_ID,
            ],
        )


def _probe_local_path_collision() -> ProbeResult:
    """P4: bundle's image_manifest_spec has a d_one_local entry AND a
    local_asset entry sharing the same local_path; the runner's
    _check_local_path_collision gate fires."""
    shared_path = "media/shared_collision.png"
    collision_manifest = {
        "images": [
            {
                "id": D_ONE_IMAGE_ID,
                "local_path": shared_path,
                "source": "d_one_local",
                "alt_text": "Generated accent (collision probe).",
                "intended_use": "spot illustration",
            },
            {
                "id": LOCAL_ASSET_IMAGE_ID,
                "local_path": shared_path,  # same as the d_one_local entry.
                "source": "local_asset",
                "alt_text": "Caller accent (collision probe).",
                "intended_use": "spot illustration",
            },
        ],
    }
    with tempfile.TemporaryDirectory(
        prefix="szh_mixed_smoke_p4_",
    ) as raw_td:
        td = Path(raw_td)
        bundle = _materialize_bundle(
            td,
            image_manifest_spec_overrides=collision_manifest,
            local_asset_dst_local_path=shared_path,
        )
        # Rewrite the slide_specs so each cover references an existing
        # image_ref (the manifest still declares both ids, just at the
        # same local_path — the lane-collision gate fires before any
        # slide-level check kicks in). Use the canonical local_paths in
        # plan/slides; only the manifest's local_path was perturbed.
        return _probe_runner_fails(
            name=(
                "P4: d_one_local / local_asset local_path collision -> "
                "_check_local_path_collision refuses"
            ),
            td=td,
            bundle_dir=bundle["bundle"],
            expected_substrings=[
                "local_path", "d_one_local", "local_asset",
            ],
        )


