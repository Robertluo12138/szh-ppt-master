def _run_self_test() -> int:
    print(
        "=== mixed image-asset pipeline smoke "
        "(mock chain; real D-One UNVERIFIED) ==="
    )
    if not TEMPLATE_ROOT.is_dir():
        print(
            f"FAIL: template root not found at {TEMPLATE_ROOT}; the "
            f"smoke requires the committed business_review template.",
            file=sys.stderr,
        )
        return 1
    if not RUN_MOCK_IMAGE_PIPELINE.is_file():
        print(
            f"FAIL: scripts/run_mock_image_pipeline.py not found at "
            f"{RUN_MOCK_IMAGE_PIPELINE}",
            file=sys.stderr,
        )
        return 1
    tree_before = _snapshot_committed_tree()

    with tempfile.TemporaryDirectory(
        prefix="szh_mixed_image_asset_pipeline_smoke_",
    ) as raw_td:
        td = Path(raw_td)
        print(f"  tempdir: {td}")
        print()
        positive_ok, positive_results = _run_positive_chain(td)
        print()
        print("--- positive assertions ---")
        fails = 0
        for a in positive_results:
            mark = "PASS" if a.ok else "FAIL"
            suffix = f" -- {a.detail}" if not a.ok and a.detail else ""
            print(f"  [{mark}] {a.name}{suffix}")
            if not a.ok:
                fails += 1
        print()
        if not positive_ok or fails:
            print(
                f"FAIL: positive proof did not hold "
                f"({fails} assertion(s) failed).",
                file=sys.stderr,
            )
            _check_repo_unchanged(tree_before)
            return 1

    print("--- negative probes ---")
    probes: list[ProbeResult] = [
        _probe_missing_source_assets(),
        _probe_wrong_local_asset_magic(),
        _probe_local_asset_id_in_d_one_spec(),
        _probe_local_path_collision(),
    ]
    fails = 0
    for r in probes:
        mark = "PASS" if r.ok else "FAIL"
        suffix = f" -- {r.detail}" if not r.ok and r.detail else ""
        print(f"  [{mark}] {r.name}{suffix}")
        if not r.ok:
            fails += 1

    rc_snapshot = _check_repo_unchanged(tree_before)
    if fails or rc_snapshot != 0:
        print(
            f"\nFAIL: {fails} negative probe(s) did not fire as "
            f"documented; snapshot rc={rc_snapshot}.",
            file=sys.stderr,
        )
        return 1

    print()
    print(
        "OK (self-test): mixed image-asset pipeline smoke passed.\n"
        f"  Real D-One status: {REAL_D_ONE_STATUS}"
    )
    return 0


