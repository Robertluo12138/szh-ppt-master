#!/usr/bin/env python3
"""mixed_image_asset_pipeline_smoke.py

Stdlib-only, tempdir-only acceptance smoke for the **mixed image-asset
lane** through ``scripts/run_mock_image_pipeline.py``. Constructs its
own synthetic bundle under a single ``tempfile.TemporaryDirectory()``
containing TWO cover slides — one referencing a ``d_one_local`` image
(mock-generated bytes via the local D-One stub chain) AND one
referencing a ``local_asset`` image (caller-supplied PNG bytes staged
through ``<bundle>/source_assets/``) — drives the runner end-to-end,
and asserts the documented happy-path invariants. Then runs four
fail-closed probes (missing ``source_assets``, wrong ``local_asset``
magic bytes, ``local_asset`` id leaking into ``d_one_spec``, and a
``d_one_local`` / ``local_asset`` ``local_path`` collision) each in its
own tempdir; each must exit non-zero AND leave no ``.pptx`` at the
nominated ``--output`` path.

MOCK / STUB ONLY — NOT real D-One integration. Nothing in this script
calls D-One, MCP, Qoder, a public network, telemetry, any model API,
an image search, a browser, or any external service. The PNG bytes
inlined here (the local_asset payload) and the synthetic PNG produced
by the d_one_local lane are both minimal magic-byte-valid local
payloads; neither is a photographically meaningful image. Real D-One
remains UNVERIFIED.

Positive-chain post-conditions:

  * ``scripts/run_mock_image_pipeline.py`` returns rc=0 against the
    bundle.
  * The produced ``--output`` ``.pptx`` exists as a regular non-symlink
    non-empty file.
  * ``scripts/validate_pptx_contract.py --pptx <out>
    --expected-slide-count 2`` returns rc=0 and emits ``[PASS]`` for
    every ``minimal_evidence.*`` gate the goal pins.
  * ``<report-dir>/inventory.json`` exists, ``ok == True``,
    ``findings == []``, ``slide_count == 2``, and ``media_parts``
    holds AT LEAST TWO internal ``ppt/media/*`` entries whose
    extensions are in ``{.png, .jpg, .jpeg}``.
  * No relationship inside the produced PPTX carries an external
    ``TargetMode``, a URI scheme, ``file://``, ``data:`` scheme, or any
    other scheme prefix (smoke-owned zipfile walk against every
    ``.rels`` part, defense-in-depth alongside the inventory's
    ``relationships.external`` / ``relationships.file_uri`` finding
    codes).
  * The caller-staged ``local_asset`` PNG sha256 appears in
    ``inventory.media_parts[].sha256`` (proves the local_asset lane
    landed byte-identical inside the package, not a copy that was
    re-encoded / metadata-stamped on the way through).
  * The generated mock D-One media sha256 is byte-distinct from the
    local_asset sha256 (proves the two lanes carry independent bytes
    end-to-end, not a collapse where one lane's bytes overwrote the
    other).
  * ``<report-dir>/mock_d_one_adapter_plan.json`` exists, parses as
    JSON, and its ``requests[]`` set is EXACTLY the d_one_local id —
    the local_asset id MUST NOT appear (the sidecar is the audit
    surface for what the mock D-One adapter generated; a local_asset
    id leaking into the sidecar would falsely claim the caller-staged
    bytes were a generated artifact).

Fail-closed probes (each runs in its own tempdir; each must exit
non-zero AND leave no PPTX at the nominated ``--output``):

  P1   missing source_assets — bundle declares a local_asset entry but
       ships no ``<bundle>/source_assets/`` AND no
       ``--source-assets-dir`` flag was passed; the runner refuses at
       its own boundary before any subprocess fires.

  P2   wrong local_asset magic bytes — bundle ships
       ``<bundle>/source_assets/<local_path>`` whose first bytes do
       NOT match the PNG signature; the runner's
       ``_stage_local_assets`` magic-byte gate fires.

  P3   local_asset id leaks into d_one_spec — bundle's
       ``d_one_spec.json`` lists the local_asset manifest id as a
       request; the runner's ``_check_d_one_spec_covers_generated``
       leaked-local-asset gate fires.

  P4   d_one_local / local_asset local_path collision — bundle's
       ``image_manifest_spec.json`` has a d_one_local entry AND a
       local_asset entry that share the same ``local_path``; the
       runner's ``_check_local_path_collision`` gate fires.

Snapshot check: every scenario runs under
``tempfile.TemporaryDirectory()`` with ``TMPDIR=/tmp``. Before the
first scenario the smoke snapshots every committed top-level entry
under ``REPO_ROOT`` (regular files hashed by bytes, directories walked
recursively, symlinks recorded by readlink target). After the last
scenario the snapshot must match byte-for-byte — proves no artifact
(``.pptx`` / inventory / sidecar / report / ``__pycache__`` / package
zip / temp residue) lands under any committed surface.

Stdlib only. NETWORK-FREE. NO real D-One. NO MCP. NO Qoder. NO model
API. NO image search. NO telemetry.
"""
