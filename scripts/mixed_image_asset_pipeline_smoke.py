@dataclass
class Assertion:
    name: str
    ok: bool
    detail: str = ""


def _list_pptx_media_parts(pptx: Path) -> tuple[list[str], Exception | None]:
    try:
        zf = zipfile.ZipFile(pptx, "r")
    except (zipfile.BadZipFile, OSError) as exc:
        return [], exc
    try:
        names = zf.namelist()
    finally:
        zf.close()
    return sorted(
        n for n in names
        if n.startswith("ppt/media/")
        and Path(n).suffix.lower() in _EMBEDDABLE_MEDIA_EXTS
    ), None


def _pptx_media_shas(pptx: Path) -> tuple[dict[str, str], Exception | None]:
    """Return (part -> sha256) for every embeddable ppt/media/* part."""
    media, err = _list_pptx_media_parts(pptx)
    if err is not None:
        return {}, err
    out: dict[str, str] = {}
    try:
        zf = zipfile.ZipFile(pptx, "r")
    except (zipfile.BadZipFile, OSError) as exc:
        return {}, exc
    try:
        for n in media:
            try:
                payload = zf.read(n)
            except (KeyError, OSError):
                continue
            out[n] = hashlib.sha256(payload).hexdigest()
    finally:
        zf.close()
    return out, None


def _assert_pptx_relationships_internal_only(
    pptx: Path,
) -> list[Assertion]:
    results: list[Assertion] = []
    try:
        zf = zipfile.ZipFile(pptx, "r")
    except (zipfile.BadZipFile, OSError) as exc:
        results.append(Assertion(
            "PPTX opens as ZIP for relationships walk",
            False, f"{type(exc).__name__}: {exc}",
        ))
        return results
    try:
        external: list[str] = []
        rel_tag = f"{{{_NS_REL}}}Relationship"
        for n in zf.namelist():
            if not n.endswith(".rels"):
                continue
            try:
                root = ET.fromstring(zf.read(n))
            except (KeyError, OSError, ET.ParseError) as exc:
                external.append(
                    f"{n}: cannot parse: {type(exc).__name__}: {exc}"
                )
                continue
            for el in root:
                if el.tag != rel_tag:
                    continue
                target = el.attrib.get("Target", "")
                mode = el.attrib.get("TargetMode", "")
                if mode and mode != "Internal":
                    external.append(
                        f"{n}: id={el.attrib.get('Id')!r} "
                        f"TargetMode={mode!r} Target={target!r}"
                    )
                    continue
                if _URI_SCHEME_PREFIX.match(target):
                    external.append(
                        f"{n}: id={el.attrib.get('Id')!r} "
                        f"Target={target!r} (URI scheme)"
                    )
        results.append(Assertion(
            "PPTX has no external / file:// / data: / URI-scheme "
            "relationships",
            not external,
            "; ".join(external),
        ))
    finally:
        zf.close()
    return results


def _assert_contract_minimal_evidence_pass(
    outcome: ToolOutcome,
) -> list[Assertion]:
    results: list[Assertion] = []
    out = outcome.combined
    for gate in (
        "minimal_evidence.editable_text",
        "minimal_evidence.not_all_image_slide",
        "minimal_evidence.no_blank_slide",
        "minimal_evidence.every_slide_has_native_shape",
    ):
        marker = f"[PASS] {gate}"
        results.append(Assertion(
            f"validate_pptx_contract emits [PASS] for {gate}",
            marker in out,
            f"marker {marker!r} not in validator output; "
            f"tail={out.splitlines()[-15:]!r}",
        ))
    return results


def _assert_inventory_contract(
    *, inventory_path: Path, local_asset_sha: str,
) -> tuple[list[Assertion], set[str]]:
    """Open inventory.json and assert the documented gates plus the
    mixed-lane post-conditions. Returns (assertions, media_shas) so the
    caller can compare media_shas against the local_asset sha + the
    independently observed generated-media sha for the lane-distinctness
    check."""
    results: list[Assertion] = []
    media_shas: set[str] = set()
    inv_is_file = (
        inventory_path.is_file() and not inventory_path.is_symlink()
    )
    results.append(Assertion(
        "inventory.json exists as a regular non-symlink file",
        inv_is_file, f"path={inventory_path}",
    ))
    if not inv_is_file:
        return results, media_shas
    try:
        inv = json.loads(inventory_path.read_text())
    except (json.JSONDecodeError, OSError) as exc:
        results.append(Assertion(
            "inventory.json parses as JSON",
            False, f"{type(exc).__name__}: {exc}",
        ))
        return results, media_shas
    results.append(Assertion(
        "inventory.ok is True",
        inv.get("ok") is True, f"got {inv.get('ok')!r}",
    ))
    results.append(Assertion(
        "inventory.findings is []",
        inv.get("findings") == [], f"got {inv.get('findings')!r}",
    ))
    results.append(Assertion(
        "inventory.slide_count == 2",
        inv.get("slide_count") == 2, f"got {inv.get('slide_count')!r}",
    ))
    results.append(Assertion(
        "inventory.evidence_basis matches the documented line",
        inv.get("evidence_basis") == EXPECTED_EVIDENCE_BASIS,
        f"got {inv.get('evidence_basis')!r}",
    ))
    mp = inv.get("media_parts")
    is_list = isinstance(mp, list)
    if is_list:
        for entry in mp:
            if not isinstance(entry, dict):
                continue
            sha = entry.get("sha256")
            part = entry.get("part")
            ext = entry.get("extension")
            if (
                isinstance(sha, str)
                and isinstance(part, str)
                and part.startswith("ppt/media/")
                and isinstance(ext, str)
                and "." + ext.lower() in _EMBEDDABLE_MEDIA_EXTS
            ):
                media_shas.add(sha)
    embeddable_count = len(media_shas)
    results.append(Assertion(
        "inventory.media_parts has >= 2 internal "
        "PNG/JPG/JPEG entries",
        is_list and embeddable_count >= 2,
        f"embeddable_count={embeddable_count}, media_parts={mp!r}",
    ))
    results.append(Assertion(
        "local_asset sha256 appears in inventory.media_parts[].sha256",
        local_asset_sha in media_shas,
        f"local_asset_sha={local_asset_sha!r}, "
        f"media_shas={sorted(media_shas)!r}",
    ))
    return results, media_shas


def _assert_sidecar_covers_only_d_one(
    sidecar_path: Path,
) -> list[Assertion]:
    results: list[Assertion] = []
    is_file = sidecar_path.is_file() and not sidecar_path.is_symlink()
    results.append(Assertion(
        f"sidecar {SIDECAR_FILENAME} exists as a regular non-symlink "
        f"file under --report-dir",
        is_file, f"path={sidecar_path}",
    ))
    if not is_file:
        return results
    try:
        body = json.loads(sidecar_path.read_text())
    except (json.JSONDecodeError, OSError) as exc:
        results.append(Assertion(
            f"sidecar {SIDECAR_FILENAME} parses as JSON",
            False, f"{type(exc).__name__}: {exc}",
        ))
        return results
    reqs = body.get("requests")
    ids: list[str] = []
    if isinstance(reqs, list):
        for r in reqs:
            if isinstance(r, dict) and isinstance(r.get("id"), str):
                ids.append(r["id"])
    results.append(Assertion(
        "sidecar requests[].id == [D_ONE_IMAGE_ID] exactly "
        "(d_one_local lane only)",
        ids == [D_ONE_IMAGE_ID],
        f"got requests ids={ids!r}",
    ))
    results.append(Assertion(
        "sidecar requests[] does NOT carry the local_asset id "
        "(caller-staged bytes are not a generated artifact)",
        LOCAL_ASSET_IMAGE_ID not in ids,
        f"got requests ids={ids!r}",
    ))
    return results


